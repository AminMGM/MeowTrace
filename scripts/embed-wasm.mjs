// Embeds the prebuilt core (src/renderer/src/engine/meowtrace_core.wasm) as a
// base64 module so the renderer can compile it without fetch() — which does
// not work for file:// URLs in packaged Electron apps. Runs before dev/build.
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const wasm = readFileSync(resolve('src/renderer/src/engine/meowtrace_core.wasm'))
const out = resolve('src/renderer/src/engine/core-wasm.ts')
writeFileSync(
  out,
  `// Generated by scripts/embed-wasm.mjs — do not edit.\nexport const CORE_WASM_BASE64 =\n  '${wasm.toString('base64')}'\n`
)
console.log(`embedded core: ${(wasm.length / 1024).toFixed(0)} KB`)
